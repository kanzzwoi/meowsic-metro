/**
 * Static index of every searchable settings item, built from the
 * settings-search inventory (see ~/workspace/drafts/meowsic-settings-search-inventory.md).
 * One def per item; the real item text (title + description + group + choices)
 * IS the search index, exactly like Metrolist's settings registry.
 *
 * Known gaps (not fixed here): dynamic descriptions (active choice label,
 * slider value, file size) and per-provider model ids / the 77 target
 * languages have no field in this def and are therefore not searchable;
 * R.plurals.seconds (crossfade duration) is not represented. Hardcoded
 * choice labels that ARE indexed: provider names, HTTP/SOCKS, density
 * labels (choiceLiterals); the "DeepL " title prefix is kept via
 * titlePrefix so the two API-key rows stay distinguishable.
 */

