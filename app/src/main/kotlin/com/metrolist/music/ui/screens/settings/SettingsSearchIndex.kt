fun settingsSearchItemDef(itemId: String): SettingsSearchItemDef? =
    settingsSearchItemDefs.firstOrNull { it.itemId == itemId }

/** One icon per screen (drawables already used on that screen), except the
 * alarm items, which keep the exact icons from AlarmSettingsSection. */
private fun settingsSearchIconRes(def: SettingsSearchItemDef): Int =
    when (def.itemId) {
        "alarm_add" -> R.drawable.add_circle
        "alarm_empty" -> R.drawable.bedtime
        "alarm_exact_permission", "alarm_battery_optimization" -> R.drawable.warning
        else -> when (def.route) {
            "settings/appearance" -> R.drawable.palette
            "settings/content" -> R.drawable.language
            "settings/player" -> R.drawable.play
            "settings/ai" -> R.drawable.translate
            "settings/privacy" -> R.drawable.security
            "settings/storage" -> R.drawable.storage
            else -> R.drawable.settings
        }
    }

private fun settingsSearchPageTitleRes(route: String): Int =
    when (route) {
        "settings/appearance" -> R.string.appearance
        "settings/content" -> R.string.content
        "settings/player" -> R.string.player_and_audio
        "settings/ai" -> R.string.ai_lyrics_translation
        "settings/privacy" -> R.string.privacy
        "settings/storage" -> R.string.storage
        else -> R.string.settings
    }

@Composable
fun rememberSettingsSearchItems(navController: NavController): List<SettingsSearchEntry> {
    return settingsSearchItemDefs.map { def ->
        SettingsSearchEntry(
            title = (def.titlePrefix ?: "") +
                (def.titleLiteral ?: stringResource(def.titleRes!!)),
            subtitle = def.descLiteral ?: def.descRes?.let { stringResource(it) },
            group = def.groupLiteral ?: def.groupRes?.let { stringResource(it) },
            choices = def.choiceRes.map { stringResource(it) } + def.choiceLiterals,
            icon = painterResource(settingsSearchIconRes(def)),
            onClick = {
                navController.navigate(
                    "${def.route}?item=${def.itemId}&group=${def.groupAnchorId}" +
                        (def.dialog?.let { "&dialog=$it" } ?: ""),
                )
            },
            itemId = def.itemId,
            dialog = def.dialog,
            pageTitle = stringResource(settingsSearchPageTitleRes(def.route)),
        )
    }
}
